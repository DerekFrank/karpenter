#!/usr/bin/env bash
set -euo pipefail

# This script ensures that we get all the directories that contain an "action.yaml" composite action
# and make sure that we have a dependabot entry for them. Currently, dependabot doesn't support wildcarding
# composite actions in a way that enables us to set a single entry for them. Instead, you need to grab all directories
# that contain actions that you want to auto-update and add an entry for each one in "dependabot.yaml"
# https://github.com/dependabot/dependabot-core/issues/6704

DEPENDABOT_FILE=.github/dependabot.yaml
STATIC_ENTRIES=2 # The number of manually configured dependabot entries at the top of the file

# Head comment attached to the first generated entry. Truncating the generated entries drops it, so it is re-applied below.
GENERATED_COMMENT="Everything under this line is currently auto-generated by hack/dependabot.sh
This needs to be generated since composite actions are currently not supported for auto-updates
through dependabot without explicitly setting their directory: https://github.com/dependabot/dependabot-core/issues/6704
If you need to make a change to this file, ensure that you make a change to hack/dependabot.sh first
That script assumes that the number of elements above this line is static and bases the append operation on it"

# Reset to the static entries so that entries for removed actions don't persist
n=$STATIC_ENTRIES yq -i '.updates |= .[0:env(n)]' "${DEPENDABOT_FILE}"

DIRS=($(find .github/actions -name "action.yaml" -type f -print0 | xargs -0 dirname | sort))
for DIR in "${DIRS[@]}"; do
  dir=$DIR yq -i '.updates += [{"package-ecosystem": "github-actions", "directory": env(dir), "schedule": {"interval": "weekly"}, "groups": {"action-deps": {"patterns": ["*"]}}}]' "${DEPENDABOT_FILE}"
done

if [[ ${#DIRS[@]} -gt 0 ]]; then
  n=$STATIC_ENTRIES comment=$GENERATED_COMMENT yq -i '.updates[env(n)] head_comment = strenv(comment)' "${DEPENDABOT_FILE}"
fi
